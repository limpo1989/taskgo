package benchmarks

import (
	"syscall"
	"time"
)

// cpuTime is the process CPU time spent so far, user and system alike, so a
// scenario can report what a pool costs beyond the wall clock. It mirrors the
// helper of the taskpool comparison suite these scenarios were ported from.
func cpuTime() time.Duration {
	var ru syscall.Rusage
	if err := syscall.Getrusage(syscall.RUSAGE_SELF, &ru); err != nil {
		return 0
	}
	user := time.Duration(ru.Utime.Sec)*time.Second + time.Duration(ru.Utime.Usec)*time.Microsecond
	sys := time.Duration(ru.Stime.Sec)*time.Second + time.Duration(ru.Stime.Usec)*time.Microsecond
	return user + sys
}
